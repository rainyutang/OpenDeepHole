"""HTTP bindings for scan skills."""

from fastapi import APIRouter, Depends
from backend.auth import get_current_user
from backend.models import User
from backend.report_routes import HistoricalReportRoute
from backend.scans import skills as service

router = APIRouter(route_class=HistoricalReportRoute)


@router.get("/api/scan/{scan_id}/skill/{vuln_type}")
async def get_scan_skill(
    scan_id: str,
    vuln_type: str,
    current_user: User = Depends(get_current_user),
) -> dict:
    'Get the SKILL/prompt content for a vuln_type, merged with scan feedback.\n\n    Reads directly from the checker registry (not the workspace) so it works\n    regardless of where the agent runs.  Feedback entries associated with\n    this scan are merged into a "历史用户经验" section, same as the agent\n    workspace builder does.\n    '
    return await service.get_scan_skill(scan_id=scan_id, vuln_type=vuln_type, current_user=current_user)


@router.get("/api/scan/{scan_id}/skill-reports")
async def get_scan_skill_reports(
    scan_id: str,
    checker_name: str | None = None,
    current_user: User = Depends(get_current_user),
) -> dict:
    'Return Markdown reports generated by report-mode user SKILLs.'
    return await service.get_scan_skill_reports(scan_id=scan_id, checker_name=checker_name, current_user=current_user)


@router.get("/api/scan/{scan_id}/fp-review/skill")
async def get_fp_review_skill(
    scan_id: str,
    current_user: User = Depends(get_current_user),
) -> dict:
    'Return the FP review skill content, merged with user feedback for this scan.'
    return await service.get_fp_review_skill(scan_id=scan_id, current_user=current_user)
