"""HTTP boundary for scan artifacts."""
from __future__ import annotations
from fastapi import Query, APIRouter, Depends
from backend.models import (
    AgentGitHistory,
    HistoryPattern,
    ThreatAuditTask,
    ThreatPatternAuditTask,
    VulnerabilityPage,
)
from backend.file_inventory import FileInventoryUpload
from backend.report_routes import HistoricalReportRoute, ApplicationRoute
import backend.scans.ingestion.artifacts as service

router = APIRouter(prefix="/api/agent", route_class=HistoricalReportRoute)
public_router = APIRouter(route_class=ApplicationRoute)


@router.post('/scan/{scan_id}/git_history')
async def agent_push_git_history(scan_id: str, body: AgentGitHistory) -> dict:
    'Agent uploads the mined git-history security problem patterns for a scan.'
    return await service.agent_push_git_history(scan_id=scan_id, body=body)


@router.get('/scan/{scan_id}/git_history')
async def agent_get_git_history(scan_id: str) -> list[HistoryPattern]:
    'Return the mined git-history patterns for a scan (used by FP review).'
    return await service.agent_get_git_history(scan_id=scan_id)


@router.post('/scan/{scan_id}/file-inventory')
async def agent_push_file_inventory(scan_id: str, body: FileInventoryUpload) -> dict:
    return await service.agent_push_file_inventory(scan_id=scan_id, body=body)


@router.get('/scan/{scan_id}/file-inventory', response_model=dict)
async def agent_get_file_inventory(scan_id: str) -> dict:
    return await service.agent_get_file_inventory(scan_id=scan_id)


@router.post('/scan/{scan_id}/threat-analysis')
async def agent_push_threat_analysis(scan_id: str, body: dict) -> dict:
    'Agent uploads an opaque bundle of threat-analysis artifacts.'
    return await service.agent_push_threat_analysis(scan_id=scan_id, body=body)


@router.get('/scan/{scan_id}/threat-analysis', response_model=dict)
async def agent_get_threat_analysis(scan_id: str) -> dict:
    'Return the stored threat-analysis artifact bundle.'
    return await service.agent_get_threat_analysis(scan_id=scan_id)


@router.post('/scan/{scan_id}/threat-audit-task')
async def agent_upsert_threat_audit_task(scan_id: str, body: dict) -> dict:
    'Agent creates or updates one threat-analysis-derived audit task.'
    return await service.agent_upsert_threat_audit_task(scan_id=scan_id, body=body)


@router.get('/scan/{scan_id}/threat-audit-tasks', response_model=list[ThreatAuditTask])
async def agent_list_threat_audit_tasks(scan_id: str) -> list[ThreatAuditTask]:
    'Return threat-analysis-derived audit tasks for scan resume.'
    return await service.agent_list_threat_audit_tasks(scan_id=scan_id)


@router.post('/scan/{scan_id}/threat-pattern-audit-task')
async def agent_upsert_threat_pattern_audit_task(scan_id: str, body: dict) -> dict:
    'Agent creates or updates one module/pattern audit task.'
    return await service.agent_upsert_threat_pattern_audit_task(scan_id=scan_id, body=body)


@router.get('/scan/{scan_id}/threat-pattern-audit-tasks', response_model=list[ThreatPatternAuditTask])
async def agent_list_threat_pattern_audit_tasks(scan_id: str) -> list[ThreatPatternAuditTask]:
    'Return module/pattern audit tasks for scan resume.'
    return await service.agent_list_threat_pattern_audit_tasks(scan_id=scan_id)


@router.get('/scan/{scan_id}/vulnerabilities', response_model=VulnerabilityPage)
async def agent_list_vulnerabilities(
    scan_id: str,
    limit: int=Query(500, ge=1, le=500),
    after: int=Query(-1, ge=-1),
) -> VulnerabilityPage:
    'Return persisted findings used by Agent resume-time deduplication.'
    return await service.agent_list_vulnerabilities(scan_id=scan_id, limit=limit, after=after)


@router.post('/scan/{scan_id}/skill-report')
async def agent_replace_skill_reports(scan_id: str, body: dict) -> dict:
    'Agent replaces Markdown reports generated by one report-mode SKILL.'
    return await service.agent_replace_skill_reports(scan_id=scan_id, body=body)
